/**
 * One-off move of the legacy free-text tags to the canonical tag system (task 2.3), shared by
 * `scripts/migrate-tags.ts` and its integration test. Idempotent: a second run changes nothing.
 *
 * 1. Every tag gets a canonical target slug: the taxonomy slug when its name, translations or
 *    slug resolve in the taxonomy (`c++` -> `cpp`), else the canonical form of its name.
 * 2. Tags with the same target are merged (links, aliases and children move; no link is lost),
 *    and broken slugs (`c-`) are renamed.
 * 3. Uncurated tags (kind TOPIC, no parent, no icon) get the taxonomy name, kind, parent and
 *    aliases; missing ancestors are created. Copied translations equal to the name are cleared.
 * 4. Each SiteSettings.skills entry becomes a tag (the column itself stays, approved).
 */
import type { Prisma } from "@prisma/client";
import { canonicalize } from "./normalize";
import { taxonomyNode } from "./taxonomy";
import { mergeTags, TagResolver } from "./service";

type Tx = Prisma.TransactionClient;

export interface MigrationReport {
  merged: { from: string; into: string }[];
  renamed: { from: string; to: string }[];
  curated: { slug: string; name: string; parent: string | null }[];
  clearedTranslations: string[];
  createdFromSettings: string[];
  createdAncestors: string[];
}

interface LegacyTag {
  id: string;
  slug: string;
  name: string;
  nameTr: string | null;
  nameEn: string | null;
  createdAt: Date;
}

function targetSlug(tag: LegacyTag): string {
  const candidates = [tag.name, tag.nameEn, tag.nameTr, tag.slug].filter((value): value is string =>
    Boolean(value),
  );
  for (const value of candidates) {
    const key = canonicalize(value);
    const node = key && taxonomyNode(key);
    if (node) return node.slug;
  }
  return canonicalize(tag.name) ?? canonicalize(tag.slug) ?? tag.slug;
}

const sameText = (a: string | null, b: string) =>
  a !== null && a.trim().toLocaleLowerCase("tr") === b.trim().toLocaleLowerCase("tr");

export async function migrateTags(tx: Tx): Promise<MigrationReport> {
  const report: MigrationReport = {
    merged: [],
    renamed: [],
    curated: [],
    clearedTranslations: [],
    createdFromSettings: [],
    createdAncestors: [],
  };

  // --- 1-2: merge and rename ------------------------------------------------------------------
  const legacy = await tx.tag.findMany({
    select: { id: true, slug: true, name: true, nameTr: true, nameEn: true, createdAt: true },
    orderBy: [{ createdAt: "asc" }, { id: "asc" }],
  });
  const aliasOwner = new Map(
    (await tx.tagAlias.findMany({ select: { alias: true, tagId: true } })).map((a) => [
      a.alias,
      a.tagId,
    ]),
  );
  const groups = new Map<string, LegacyTag[]>();
  for (const tag of legacy) {
    const target = targetSlug(tag);
    groups.set(target, [...(groups.get(target) ?? []), tag]);
  }
  for (const [target, tags] of groups) {
    const ownerId = aliasOwner.get(target);
    const survivor =
      tags.find((t) => t.slug === target) ??
      (ownerId ? legacy.find((t) => t.id === ownerId) : undefined) ??
      tags[0]!;
    for (const tag of tags) {
      if (tag.id === survivor.id) continue;
      await mergeTags(tx, tag.id, survivor.id);
      report.merged.push({ from: tag.slug, into: survivor.slug });
    }
    if (survivor.slug !== target && !ownerId) {
      // No alias for the old slug: legacy slugs were generated by stripping non-ASCII letters
      // ("g-m-l-yaz-l-m") and no public page linked to them.
      await tx.tag.update({ where: { id: survivor.id }, data: { slug: target } });
      report.renamed.push({ from: survivor.slug, to: target });
    }
  }

  // --- 3: taxonomy and translations -----------------------------------------------------------
  const before = new Set((await tx.tag.findMany({ select: { slug: true } })).map((t) => t.slug));
  const resolver = await TagResolver.load(tx);
  const tags = await tx.tag.findMany({
    select: {
      id: true,
      slug: true,
      name: true,
      nameTr: true,
      nameEn: true,
      kind: true,
      parentId: true,
      icon: true,
      _count: { select: { aliases: true } },
    },
    orderBy: { slug: "asc" },
  });
  for (const tag of tags) {
    const node = taxonomyNode(tag.slug);
    const uncurated =
      tag.kind === "TOPIC" && tag.parentId === null && tag.icon === null && tag._count.aliases <= 1;
    if (node && node.slug === tag.slug && uncurated) {
      const parent = node.parent ? await resolver.ensure(node.parent) : null;
      const data = {
        name: node.name,
        nameTr: node.nameTr ?? null,
        nameEn: node.nameEn ?? null,
        kind: node.kind,
        isSkill: node.isSkill ?? true,
        icon: node.icon ?? null,
        parentId: parent?.id ?? null,
      };
      const changed =
        tag.name !== data.name ||
        tag.nameTr !== data.nameTr ||
        tag.nameEn !== data.nameEn ||
        tag.kind !== data.kind ||
        tag.parentId !== data.parentId ||
        tag.icon !== data.icon;
      if (changed) {
        await tx.tag.update({ where: { id: tag.id }, data });
        report.curated.push({ slug: tag.slug, name: node.name, parent: node.parent ?? null });
      }
      const taken = new Set(
        (await tx.tagAlias.findMany({ select: { alias: true } })).map((a) => a.alias),
      );
      const slugs = new Set((await tx.tag.findMany({ select: { slug: true } })).map((t) => t.slug));
      const free = (node.aliases ?? []).filter((a) => !taken.has(a) && !slugs.has(a));
      if (free.length > 0) {
        await tx.tagAlias.createMany({ data: free.map((alias) => ({ alias, tagId: tag.id })) });
      }
    } else if (!node && sameText(tag.nameTr, tag.name) && sameText(tag.nameEn, tag.name)) {
      await tx.tag.update({ where: { id: tag.id }, data: { nameTr: null, nameEn: null } });
      report.clearedTranslations.push(tag.slug);
    }
  }

  // --- 4: SiteSettings.skills -----------------------------------------------------------------
  const settings = await tx.siteSettings.findFirst({ select: { skills: true } });
  const skills = Array.isArray(settings?.skills) ? settings.skills : [];
  for (const entry of skills) {
    if (!entry || typeof entry !== "object" || Array.isArray(entry)) continue;
    const { nameTr, nameEn } = entry as { nameTr?: unknown; nameEn?: unknown };
    const en = typeof nameEn === "string" ? nameEn.trim() : "";
    const tr = typeof nameTr === "string" ? nameTr.trim() : "";
    const name = en || tr;
    if (!name) continue;
    const translated = Boolean(en && tr && !sameText(tr, en));
    const known = resolver.resolve(name) ?? (tr ? resolver.resolve(tr) : null);
    if (known) continue;
    const tag = await resolver.ensure(name, {
      name,
      nameTr: translated ? tr : null,
      nameEn: translated ? en : null,
      isSkill: true,
    });
    if (tag) report.createdFromSettings.push(tag.slug);
  }

  const after = await tx.tag.findMany({ select: { slug: true } });
  report.createdAncestors = after
    .map((t) => t.slug)
    .filter((slug) => !before.has(slug) && !report.createdFromSettings.includes(slug));
  return report;
}
